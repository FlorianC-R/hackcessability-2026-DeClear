import OriginalMessage from './OriginalMessage.jsx'

// Plain-language descriptions and shapes for each urgency level. Urgency is
// conveyed by a word plus a shape symbol, never by colour alone.
const URGENCY_DISPLAY = {
  None: { label: 'No urgency', symbol: '\u25CB', note: 'Nothing time-sensitive here.' },
  Low: { label: 'Low urgency', symbol: '\u25B3', note: 'Worth noting, but not pressing.' },
  Medium: { label: 'Medium urgency', symbol: '\u25C6', note: 'Please deal with this soon.' },
  High: { label: 'High urgency', symbol: '\u25A0', note: 'This needs your attention promptly.' },
}

// Find the uncertainty note (if any) attached to a specific action or date.
function findUncertainty(indicators, kind, id) {
  return indicators.find(
    (item) => item.targetKind === kind && item.targetId === id,
  )
}

// ResultPanel shows the deterministic example output for a selected sample.
// The output is clearly labeled as a fixed example, not AI-generated content.
function ResultPanel({ result, original, isOriginalOpen, onToggleOriginal }) {
  const urgency = URGENCY_DISPLAY[result.urgencyLevel] ?? URGENCY_DISPLAY.None

  return (
    <section className="dc-result" aria-labelledby="dc-result-heading">
      <p className="dc-result__disclaimer">
        This is a fixed example explanation, written ahead of time to show how
        DeClear works. It was not generated by artificial intelligence.
      </p>
      <h2 id="dc-result-heading">What this message means</h2>

      <div className={`dc-urgency dc-urgency--${result.urgencyLevel.toLowerCase()}`}>
        <span className="dc-urgency__symbol" aria-hidden="true">
          {urgency.symbol}
        </span>
        <span className="dc-urgency__label">{urgency.label}</span>
        <span className="dc-urgency__note">{urgency.note}</span>
      </div>

      <div className="dc-block">
        <h3>Important dates</h3>
        {result.importantDates.length === 0 ? (
          <p className="dc-empty">No important dates were found.</p>
        ) : (
          <ul className="dc-list">
            {result.importantDates.map((date) => {
              const uncertainty = findUncertainty(
                result.uncertaintyIndicators,
                'importantDate',
                date.id,
              )
              return (
                <li key={date.id} className="dc-list__item">
                  <span className="dc-date__when">{date.dateText}</span>
                  <span className="dc-date__what">{date.label}</span>
                  {uncertainty && (
                    <span className="dc-uncertainty">
                      Please check: {uncertainty.label}
                    </span>
                  )}
                </li>
              )
            })}
          </ul>
        )}
      </div>

      <div className="dc-block">
        <h3>What you need to do</h3>
        {result.requiredActions.length === 0 ? (
          <p className="dc-empty">No required actions were found.</p>
        ) : (
          <ul className="dc-list">
            {result.requiredActions.map((action) => {
              const uncertainty = findUncertainty(
                result.uncertaintyIndicators,
                'requiredAction',
                action.id,
              )
              return (
                <li key={action.id} className="dc-list__item">
                  <span className="dc-action__text">{action.text}</span>
                  {uncertainty && (
                    <span className="dc-uncertainty">
                      Please check: {uncertainty.label}
                    </span>
                  )}
                </li>
              )
            })}
          </ul>
        )}
      </div>

      <div className="dc-block">
        <h3>Plain explanation</h3>
        <p className="dc-explanation">{result.explanation}</p>
      </div>

      <OriginalMessage
        original={original}
        isOpen={isOriginalOpen}
        onToggle={onToggleOriginal}
      />
    </section>
  )
}

export default ResultPanel
